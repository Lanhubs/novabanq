"""User schemas.

Pydantic models for the users feature. These models define the HTTP
contract that the mobile client codes against. Every field is
explicitly typed and documented so the OpenAPI spec generated by
FastAPI is complete.

Tag format:
    Users type only the base name (e.g. "david323"). The country suffix
    is appended server-side from the profile country. The frontend
    shows a live preview of the full tag under the input field.

Naming convention:
    *Request  — validated on incoming HTTP calls.
    *Response — serialized on outgoing HTTP responses.
"""

import re
from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.core.constants import (
    Country,
    Currency,
    PIN_LENGTH,
    TAG_ALLOWED_PATTERN,
    TAG_MAX_LENGTH,
    TAG_MIN_LENGTH,
    TAG_SUFFIX_SEPARATOR,
)


# ---------------------------------------------------------------------------
# Requests
# ---------------------------------------------------------------------------

class UserCreateRequest(BaseModel):
    """Payload sent by the client immediately after Firebase sign-up.

    All name fields are required — KYC verification later matches them
    against the government ID, so partial names will fail verification.
    """

    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")

    first_name: str = Field(
        ...,
        min_length=1,
        max_length=80,
        description="Given name as it appears on the user's government ID.",
        examples=["David"],
    )
    middle_name: str = Field(
        ...,
        min_length=1,
        max_length=80,
        description="Middle name as it appears on the user's government ID.",
        examples=["Chukwuemeka"],
    )
    last_name: str = Field(
        ...,
        min_length=1,
        max_length=80,
        description="Family name as it appears on the user's government ID.",
        examples=["Okafor"],
    )
    country: Country = Field(
        ...,
        description="Two-letter ISO country code where the user resides.",
        examples=["NG"],
    )
    phone: str = Field(
        ...,
        min_length=7,
        max_length=20,
        description="Phone number in E.164 format.",
        examples=["+2348012345678"],
    )

    @field_validator("first_name", "middle_name", "last_name")
    @classmethod
    def _validate_name(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Name fields cannot be blank.")
        if any(ch.isdigit() for ch in value):
            raise ValueError("Name fields cannot contain digits.")
        return value

    @field_validator("phone")
    @classmethod
    def _validate_phone(cls, value: str) -> str:
        if not value.startswith("+"):
            raise ValueError("Phone number must be in E.164 format (start with '+').")
        if not value[1:].isdigit():
            raise ValueError("Phone number must contain only digits after '+'.")
        return value



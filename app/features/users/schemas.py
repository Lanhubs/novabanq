class TagClaimRequest(BaseModel):
    """Payload for claiming a @tag.

    The client sends the base name only (e.g. "david323"). Any country
    suffix the client includes is stripped before validation. The
    backend appends the correct suffix from the user's profile country.
    """

    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")

    tag: str = Field(
        ...,
        min_length=TAG_MIN_LENGTH,
        max_length=TAG_MAX_LENGTH + 5,
        description=(
            "Desired base tag name. The country suffix (e.g. '.ng') is "
            "appended by the backend and must not be sent."
        ),
        examples=["david323"],
    )

    @field_validator("tag")
    @classmethod
    def _validate_tag(cls, value: str) -> str:
        normalized = value.lower().lstrip("@")
        # Strip any suffix the client mistakenly sent (e.g. "david323.ng").
        if TAG_SUFFIX_SEPARATOR in normalized:
            normalized = normalized.split(TAG_SUFFIX_SEPARATOR, 1)[0]
        if len(normalized) < TAG_MIN_LENGTH:
            raise ValueError(
                f"Tag must be at least {TAG_MIN_LENGTH} characters."
            )
        if len(normalized) > TAG_MAX_LENGTH:
            raise ValueError(
                f"Tag must be at most {TAG_MAX_LENGTH} characters."
            )
        if not re.fullmatch(TAG_ALLOWED_PATTERN, normalized):
            raise ValueError(
                "Tag may only contain lowercase letters, numbers, and underscores."
            )
        return normalized


class SetPinRequest(BaseModel):
    """Payload for setting the user's PIN."""

    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")

    pin: str = Field(
        ...,
        min_length=PIN_LENGTH,
        max_length=PIN_LENGTH,
        description=f"{PIN_LENGTH}-digit PIN.",
        examples=["48392"],
    )

    @field_validator("pin")
    @classmethod
    def _validate_pin(cls, value: str) -> str:
        if not value.isdigit():
            raise ValueError("PIN must contain only digits.")
        if len(set(value)) == 1:
            raise ValueError("PIN cannot be a single repeated digit.")
        return value



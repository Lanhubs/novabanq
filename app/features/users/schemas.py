class UserResponse(BaseModel):
    """Public user profile returned by the API."""

    model_config = ConfigDict(from_attributes=True)

    uid: str = Field(..., description="Firebase uid.")
    first_name: str = Field(..., description="Given name.")
    middle_name: str = Field(..., description="Middle name.")
    last_name: str = Field(..., description="Family name.")
    tag: str | None = Field(
        None,
        description=(
            "The user's full @tag including country suffix "
            "(without the leading '@'), or null if unclaimed."
        ),
        examples=["david323.ng"],
    )
    country: Country = Field(..., description="Two-letter ISO country code.")
    currency: Currency = Field(..., description="Default settlement currency.")
    phone: str = Field(..., description="Phone number in E.164 format.")
    email: str | None = Field(None, description="Email address, if available.")
    email_verified: bool = Field(
        False,
        description="True once the email verification OTP has been confirmed.",
    )
    phone_verified: bool = Field(
        False,
        description="True once the phone has been confirmed via SMS.",
    )
    identity_verified: bool = Field(
        False,
        description="True once BVN/national ID and face verification pass.",
    )
    account_number: str = Field(
        ...,
        description=(
            "10-digit NovaBanq account number for inbound transfers. "
            "Placeholder until real NUBANs are issued via Flutterwave."
        ),
        examples=["0172094612"],
    )
    pin_set: bool = Field(
        False,
        description="True once the user has set a transaction PIN.",
    )
    avatar_url: str | None = Field(
        None,
        description="Optional URL of the user's profile picture.",
    )
    created_at: datetime = Field(..., description="Account creation timestamp (UTC).")


